export function RiskBadge({ level, className = '' }: { level: string; className?: string }) {
  const colors: Record<string, string> = {
    CRITICAL: 'bg-red-500',
    HIGH: 'bg-orange-500',
    ELEVATED: 'bg-amber-500',
    MODERATE: 'bg-yellow-500',
    LOW: 'bg-green-500',
  };
  return (
    <span className={`px-2 py-0.5 text-xs font-medium rounded-full ${colors[level] || 'bg-surface-500'} text-white ${className}`}>
      {level}
    </span>
  );
}

export function CapacityBadge({ status, className = '' }: { status: string; className?: string }) {
  const colors: Record<string, { bg: string; text: string }> = {
    ADEQUATE: { bg: 'bg-green-50', text: 'text-green-700' },
    LIMITED: { bg: 'bg-blue-50', text: 'text-blue-700' },
    STRESSED: { bg: 'bg-amber-50', text: 'text-amber-700' },
    INSUFFICIENT: { bg: 'bg-red-50', text: 'text-red-700' },
  };
  const color = colors[status] || { bg: 'bg-surface-50', text: 'text-surface-700' };
  return (
    <span className={`px-2 py-1 text-sm font-medium rounded-full ${color.bg} ${color.text} ${className}`}>
      {status}
    </span>
  );
}

export function UtilizationBar({ 
  utilization, 
  className = '',
  height = 'h-2'
}: { 
  utilization: number; 
  className?: string;
  height?: string;
}) {
  const getColor = (util: number) => {
    if (util >= 90) return 'bg-red-500';
    if (util >= 75) return 'bg-amber-500';
    if (util >= 50) return 'bg-blue-500';
    return 'bg-green-500';
  };
  return (
    <div className={`${height} bg-surface-200 rounded-full overflow-hidden ${className}`}>
      <div
        className={`h-full rounded-full ${getColor(utilization)} transition-all duration-500`}
        style={{ width: `${Math.min(utilization, 100)}%` }}
      />
    </div>
  );
}